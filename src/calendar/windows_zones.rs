use chrono_tz::Tz;

/// The caller folds the identifier once for both feed aliases and this table.
pub(super) fn lookup_folded(id: &str) -> Option<Tz> {
    let index = WINDOWS_ZONES
        .binary_search_by_key(&id, |&(name, _)| name)
        .ok()?;
    Some(WINDOWS_ZONES[index].1)
}

